const fs=require("node:fs"),path=require("node:path"),assert=require("node:assert/strict"),vm=require("node:vm");
const source=fs.readFileSync(path.join(__dirname,"../studio/modeling-quality.js"),"utf8");
const scope={Object,Number,Math,Array,Error};
vm.runInNewContext(source.replace(/\bexport\s+/g,"")+"\nthis.api={validVisualSettings,normalizeVisualSettings,fitDistance,localContextRadius,renderQualityFlags};",scope);
const {validVisualSettings,normalizeVisualSettings,fitDistance,localContextRadius,renderQualityFlags}=scope.api;
const defaults=normalizeVisualSettings();
assert.equal(validVisualSettings(defaults),true);
assert.equal(defaults.toneCurve,"aces");
assert.equal(defaults.guide,"none");
const blue=normalizeVisualSettings({sky:"blue"});
assert.equal(blue.sky,"blue","clear blue sky must survive normalization");
assert.equal(validVisualSettings(blue),true,"blue sky is a valid persisted render profile");
assert.equal(validVisualSettings({...defaults,toneCurve:"unknown"}),false);
const a=normalizeVisualSettings({toneCurve:"neutral",sky:"warm",shadowProfile:"high",guide:"thirds"});
assert.equal(validVisualSettings(a),true);
const corrupted=normalizeVisualSettings({toneCurve:"custom",sky:"script",shadowProfile:"5000",guide:"thirds"});
assert.equal(corrupted.toneCurve,"aces");
assert.equal(corrupted.sky,"cool");
assert.equal(corrupted.guide,"thirds");
const d=fitDistance(3,45,16/9),n=fitDistance(3,45,9/16);
assert.ok(d>3 && n>d,"narrow viewport needs greater camera distance");
assert.ok(fitDistance(4,45,16/9)>d,"larger art frame needs greater distance");
assert.throws(()=>fitDistance(3,0,1),/유효하지/);
assert.equal(localContextRadius(2,400,"nearby"),12,"oversized site must not shrink nearby art frame");
assert.equal(localContextRadius(2,40,"site"),40);
assert.equal(localContextRadius(2,40,"sculpture"),2);
assert.equal(localContextRadius(10,1000,"nearby"),35);
assert.throws(()=>localContextRadius(1,2,"bad-mode"));
const problems=renderQualityFlags({width:6500,height:4000,limited:true,hasSite:false,hasArtwork:false,locked:false,shadowProfile:"high"});
assert.ok(problems.length>=5,"unsafe output combinations must flag caveats");
const clean=renderQualityFlags({width:1280,height:720,limited:false,hasSite:true,hasArtwork:true,locked:true,shadowProfile:"balanced"});
assert.equal(clean.length,0);
console.log("PASS v2.0 camera composition, scene-scale bounds, visual preset safety and render quality checks");
