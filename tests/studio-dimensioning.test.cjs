const fs=require("node:fs"),path=require("node:path"),assert=require("node:assert/strict"),vm=require("node:vm");
const source=fs.readFileSync(path.join(__dirname,"../studio/dimensioning.js"),"utf8");
const scope={Array,Number,Math,Object,Error};
vm.runInNewContext(source.replace(/\bexport\s+/g,"")+"\nthis.api={validDimensions,fitDimensionScale,anchorOffset,targetAnchorTranslation,validPlacementReference,validatePlinthDimensions};",scope);
const {validDimensions,fitDimensionScale,anchorOffset,targetAnchorTranslation,validPlacementReference,validatePlinthDimensions}=scope.api;
assert.equal(validDimensions([2,3,4]),true);
assert.equal(validDimensions([2,-3,4]),false);
const s=fitDimensionScale([2,3,4],[1,1,1],[4,6,8],"uniform-height");
assert.equal(JSON.stringify(s),JSON.stringify([2,2,2]));
assert.equal(JSON.stringify(fitDimensionScale([2,3,4],[1,1,1],[4,3,4],"uniform-width")),JSON.stringify([2,2,2]));
assert.equal(JSON.stringify(fitDimensionScale([2,3,4],[1,1,1],[4,3,4],"uniform-depth")),JSON.stringify([1,1,1]));
assert.throws(()=>fitDimensionScale([2,3,4],[1,1,1],[4,6,8],"independent"),/별도 확인/);
assert.equal(JSON.stringify(fitDimensionScale([2,3,4],[1,1,1],[4,6,12],"independent",true)),JSON.stringify([2,2,3]));
assert.throws(()=>fitDimensionScale([2,3,4],[1,1,1],[9000,6,8],"uniform-width"),/초과/);
assert.throws(()=>fitDimensionScale([0,3,4],[1,1,1],[4,6,8],"uniform-width"));
const bounds={min:[-2,0,-3],max:[2,6,3]};
assert.equal(JSON.stringify(anchorOffset(bounds,"center")),JSON.stringify([0,0,0]));
assert.equal(JSON.stringify(anchorOffset(bounds,"front-left")),JSON.stringify([-2,0,3]));
assert.equal(JSON.stringify(anchorOffset(bounds,"rear-right")),JSON.stringify([2,0,-3]));
assert.equal(JSON.stringify(targetAnchorTranslation(bounds,"front-left",[10,0,20])),JSON.stringify([12,0,17]));
assert.equal(validPlacementReference({mode:"center",position:[.5,1,2]}),true);
assert.equal(validPlacementReference({mode:"center",position:[999999,1,2]}),false);
assert.equal(validatePlinthDimensions(2,3,.4),true);
assert.equal(validatePlinthDimensions(2,3,0),false);
console.log("PASS v2.1 dimensions: proportional scale, explicit distortion, 3D anchors, plinth bounds and unsafe input rejection");